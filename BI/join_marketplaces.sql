-- 2) План (продажи/маржа) по Направление + неделя.
--    dim_plan хранит план в "длинном" формате (Направление, Показатель,
--    Неделя, Значение, Неделя Сортировка). "Неделя Сортировка" совпадает по
--    смыслу с одноимённой колонкой в dim_calendar — ключ соединения по неделям.
--
--    ВАЖНО: в dim_plan колонка "Направление" на самом деле склеивает
--    маркетплейс + направление в одну строку текстом, и написана НЕ так же,
--    как в остальных таблицах (проверено через SELECT DISTINCT):
--      'ВБ Ечипс', 'ВБ Матрасы'                        -> WB
--      'ОЗОН Digma', 'ОЗОН Аксы', 'ОЗОН Безикейность',
--      'ОЗОН Ечипс', 'ОЗОН Матрасы'                     -> Ozon
--      'Яндекс Аксы', 'Яндекс Ечипс'                    -> Yandex
--      'МВМ Ечипс'                                      -> неизвестный
--                                                          маркетплейс, в
--                                                          fact_revenue_*
--                                                          такого нет —
--                                                          сознательно не
--                                                          матчим (WHERE
--                                                          ниже отсекает по
--                                                          известному
--                                                          префиксу).
--      'общее', 'общее Ечипс'                           -> план по
--                                                          направлению
--                                                          суммарно по всем
--                                                          маркетплейсам
--                                                          (см. v_plan_total
--                                                          ниже).
--    Плюс "Ечипс" в dim_plan написано кириллицей, а в остальных таблицах
--    направление называется "Echips" латиницей — ниже отдельно переводим.
--    Из восьми показателей ("Показатель") берём только план по выручке и
--    марже (как и просили) — капитал/закупки/расходы сюда не тащим.

-- 2a) План с привязкой к конкретному маркетплейсу.
CREATE OR REPLACE VIEW v_plan_by_marketplace AS
SELECT
    "Маркетплейс",
    "Направление",
    "Неделя Сортировка",
    MAX(CASE WHEN "Показатель" = 'Выручка, план' THEN "Значение" END) AS "План Выручка, руб",
    MAX(CASE WHEN "Показатель" = 'Маржа, план'   THEN "Значение" END) AS "План Маржа, руб",
    MAX(CASE WHEN "Показатель" = 'Маржа %, план' THEN "Значение" END) AS "План Маржа, %"
FROM (
    SELECT
        CASE
            WHEN "Направление" ~ '^ВБ '     THEN 'WB'
            WHEN "Направление" ~ '^ОЗОН '   THEN 'Ozon'
            WHEN "Направление" ~ '^Яндекс ' THEN 'Yandex'
        END AS "Маркетплейс",
        CASE
            WHEN regexp_replace("Направление", '^(ВБ|ОЗОН|Яндекс) ', '') = 'Ечипс'
                THEN 'Echips'
            ELSE regexp_replace("Направление", '^(ВБ|ОЗОН|Яндекс) ', '')
        END AS "Направление",
        "Неделя Сортировка",
        "Показатель",
        "Значение"
    FROM dim_plan
    WHERE "Направление" ~ '^(ВБ|ОЗОН|Яндекс) '
) t
GROUP BY "Маркетплейс", "Направление", "Неделя Сортировка";

-- 2b) План суммарно по всем маркетплейсам (строки "общее"/"общее <Направление>").
CREATE OR REPLACE VIEW v_plan_total AS
SELECT
    NULLIF(
        CASE
            WHEN trim(regexp_replace("Направление", '^общее', '')) = 'Ечипс' THEN 'Echips'
            ELSE trim(regexp_replace("Направление", '^общее', ''))
        END,
        ''
    ) AS "Направление",
    "Неделя Сортировка",
    MAX(CASE WHEN "Показатель" = 'Выручка, план' THEN "Значение" END) AS "План Выручка (общий), руб",
    MAX(CASE WHEN "Показатель" = 'Маржа, план'   THEN "Значение" END) AS "План Маржа (общий), руб",
    MAX(CASE WHEN "Показатель" = 'Маржа %, план' THEN "Значение" END) AS "План Маржа (общий), %"
FROM dim_plan
WHERE "Направление" LIKE 'общее%'
GROUP BY 1, "Неделя Сортировка";

-- 3) Полная витрина: объединённые продажи + справочники SKU, календаря и план.
--    s.*/c.* НЕ используются целиком, т.к. дублировали бы ключевые колонки
--    ("SKU (ключ)", "Date", "Направление") из v_marketplaces_raw_union —
--    вместо этого явно перечислены остальные колонки dim_sku и dim_calendar
--    (состав проверен через \d dim_sku / \d dim_calendar после первой
--    загрузки pbi_to_postgres.py).
--
--    По повторному запросу пользователя ("а мы не смогли добавить всё в
--    единый датасет? чтобы без листов вообще было?") сюда же джойнится
--    fact_transit_receivables (dax_queries.py: "raw_transit_receivables") —
--    ТОЛЬКО по "SKU (ключ)", без Даты и Маркетплейса, т.к. сами PBI-меры
--    считаются по SKU в целом (см. комментарий в разделе 1).
--
--    ВАЖНО — эти 4 колонки НЕ грейнятся по Дате/Маркетплейсу и поэтому
--    ОДИНАКОВЫ на каждой строке SKU (для всех дат и всех трёх МП сразу).
--    Если их просто просуммировать по датам/МП в Google Sheets/сводной
--    таблице — сумма задвоится/затроится/умножится на кол-во дат. Чтобы
--    получить корректный итог по SKU, нужно брать значение из ОДНОЙ строки
--    на SKU (например MIN/MAX или любая одна строка), а не SUM() по всем.
CREATE VIEW v_marketplaces_full AS
SELECT
    u.*,
    s."Название товара",
    s."Yandex SKU",
    s."WB Артикул",
    s."WB nm_id",
    s."Ozon Артикул",
    s."Ozon SKU",
    s."На Yandex",
    s."На WB",
    s."На Ozon",
    s."SKU_upper",
    c."Год",
    c."Месяц",
    c."День",
    c."Месяц Сортировка",
    c."Неделя Сортировка",
    c."День Сортировка",
    c."Неделя (коротко)",
    c."Ярлык недели",
    pm."План Выручка, руб",
    pm."План Маржа, руб",
    pm."План Маржа, %",
    pt."План Выручка (общий), руб",
    pt."План Маржа (общий), руб",
    pt."План Маржа (общий), %",
    tr."Товаров в пути на МП, руб",
    tr."Товаров в пути на МП, шт",
    tr."Товаров в пути от поставщика, руб",
    tr."Дебиторка авансы поставщикам, руб"
FROM v_marketplaces_raw_union u
LEFT JOIN dim_sku s
    ON s."SKU (ключ)" = u."SKU (ключ)"
LEFT JOIN dim_calendar c
    ON c."Date" = u."Date"
LEFT JOIN v_plan_by_marketplace pm
    ON pm."Маркетплейс" = u."Маркетплейс"
    AND pm."Направление" = u."Направление"
    AND pm."Неделя Сортировка" = c."Неделя Сортировка"
LEFT JOIN v_plan_total pt
    ON pt."Направление" = u."Направление"
    AND pt."Неделя Сортировка" = c."Неделя Сортировка"
LEFT JOIN fact_transit_receivables tr
    ON tr."SKU (ключ)" = u."SKU (ключ)";
