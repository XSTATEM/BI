-- Замена DAX UNION из таблицы "Выгрузка Google Sheets": объединяем три сырые
-- выгрузки (fact_revenue_wb / fact_revenue_ozon / fact_revenue_yandex),
-- загруженные pbi_to_postgres.py, и подтягиваем справочники.
--
-- Ключ соединения: "SKU (ключ)" + "Date".
--
-- ФИКС (см. ошибку "column \"Выручка без НДС, руб\" does not exist"):
-- в dax_queries.py каждый DAX-запрос выгружает ОДНУ И ТУ ЖЕ меру дважды под
-- двумя разными именами колонок — "Выручка без НДС, руб" и "Выручка по
-- выкупам без НДС, руб" (обе = [Выручка без НДС] / [Выручка по выкупам без
-- НДС, руб Oz] / [... YAM]). При pandas.to_sql() с двумя одинаковыми
-- данными под разными именами в Postgres реально попала только колонка
-- "Выручка по выкупам без НДС, руб" (проверено через \d fact_revenue_wb —
-- "Выручка без НДС, руб" там физически нет). Ниже убраны все 3 обращения
-- к несуществующей короткой колонке ("Выручка без НДС, руб"), значения не
-- теряются — они и так дублировались в "Выручка по выкупам без НДС, руб".
--
-- ДРР, % — колонка удалена пользователем из всех трёх raw-выгрузок в
-- dax_queries.py (её больше нет ни в fact_revenue_wb, ни в _ozon, ни в
-- _yandex), поэтому убрана и здесь, из всех трёх SELECT.
--
-- ДЕБИТОРКА: "FR_Дебиторка с НДС, руб" = "FR_Выручка по выкупам, руб" минус
-- "FR_MP Cost с НДС, руб" — та же логика, что и меры модели PBI "Дебиторка,
-- руб WB" / "Дебиторка, руб Oz" / "Дебиторка, руб YAM" / "Дебиторка, руб"
-- (сумма по всем МП, таблица "_Меры ALL") — сверено через DAX EVALUATE ROW,
-- сумма по трём МП сходится с общей мерой. Оба слагаемых уже выгружаются во
-- всех трёх fact_revenue_* (dax_queries.py), поэтому колонка посчитана прямо
-- здесь, в Postgres — без обращения к Power BI и без повторного запуска
-- pbi_to_postgres.py.
--
-- УДАЛЕНЫ ДУБЛИКАТЫ / НЕ ВКЛЮЧЕНЫ (одно и то же значение выгружалось под
-- двумя разными именами колонок, проверено по dax_queries.py — во всех трёх
-- МП): FR_Себес УУс (= FR_Себестоимость, руб), FR_Выручка без НДС (=
-- FR_Выручка по выкупам без НДС, руб), FR_MP Cost с НДС без ", руб" (=
-- FR_MP Cost с НДС, руб), FR_Комм.маржа без НДС (= FR_Маржа, руб). Также по
-- просьбе пользователя удалены: FR_Ср. цена, руб, FR_Доля от общей выручки,
-- %, FR_Доля себестоимости, %, FR_MP Cost, %, ДРР, %, Остаток FBS, шт
-- (последняя — т.к. это остаток на складе продавца, ей место только в
-- таблице остатков, а не в выручке по МП).
--
-- ПОРЯДОК КОЛОНОК (запрос пользователя, реализовано через DROP+CREATE, т.к.
-- CREATE OR REPLACE VIEW не позволяет менять порядок/имена существующих
-- колонок — только дописывать в конец):
--   FR_Продажи, шт. → FR_Возвраты, шт. → FR_Выкупы, шт → FR_Продажи до
--   скидок с НДС → FR_Скидки МП → FR_Выручка по выкупам, руб → FR_Комиссия →
--   FR_Эквайринг → FR_Логистика прямая → FR_Обратная и прочая логистика →
--   FR_Прочие удержания → FR_Прочие списания, руб → FR_Продвижение,
--   руб → FR_Выручка по выкупам без НДС, руб → FR_MP Cost с НДС, руб →
--   FR_НДС вычет на MP Cost → FR_Маржа, руб → Остаток FBO, шт → Запас ФБО в
--   днях продажи → FR_Дебиторка с НДС, руб.
-- Дальше идёт FR_Выручка по заказам, руб (уже существовавшая колонка, не
-- входила в запрошенный список, оставлена последней).
--
-- ОБНОВЛЕНИЕ (повторный запрос пользователя, добавлено ниже):
--   • FR_Сумма возвратов, руб — теперь добавлена во все три ветки UNION.
--     Для WB настоящей рублёвой меры возвратов в модели нет, по решению
--     пользователя используется "Себестоимость возвратов WB" (см.
--     dax_queries.py) — это себестоимость, а не выручка, для Ozon/Yandex же
--     это настоящая рублёвая мера возвратов. Колонки физически появились
--     в fact_revenue_wb/ozon/yandex после повторного запуска
--     pbi_to_postgres.py.
--   • FR_Себес УУс — восстановлена (пользователь подтвердил, что это то же
--     самое значение, что и FR_Себестоимость, руб — отдельной меры "УУс" в
--     модели нет, но пользователь явно попросил вывести колонку под этим
--     именем тоже).
--   • Товаров в пути на МП, Товаров в пути от поставщика, Дебиторка авансов
--     поставщикам — по повторному запросу пользователя ("без отдельных
--     листов") добавлены прямо в v_marketplaces_full (раздел 3 ниже) через
--     LEFT JOIN к fact_transit_receivables ТОЛЬКО по SKU (без Даты и МП,
--     т.к. сами PBI-меры считаются по SKU в целом). Из-за этого значения
--     одинаковы на каждой строке SKU независимо от даты/маркетплейса — см.
--     предупреждение в комментарии перед CREATE VIEW v_marketplaces_full,
--     нельзя суммировать эти 4 колонки по датам/МП без задвоения.
--
-- FR_ПРОЧИЕ СПИСАНИЯ, РУБ — пустышка (NULL) во всех ветках UNION. Раньше на
-- этом месте была расчётная колонка "FR_Общие удержания по кабинету"
-- (COALESCE-сумма FR_Комиссия/FR_Эквайринг/FR_Логистика прямая/FR_Обратная
-- и прочая логистика/FR_Прочие удержания/FR_Продвижение) — убрана по
-- запросу пользователя, колонка временно оставлена как заглушка под будущую
-- меру.
--
-- ОСТАТОК FBO, шт (переименована и обобщена на все 3 МП, было "Остаток FBW,
-- шт" и только для WB) = "Остаток FBW, шт" для WB / "Остаток Ozon, шт" для
-- Ozon / "Остаток Yandex, шт" для Yandex (все три уже выгружаются в
-- dax_queries.py). ЗАПАС ФБО В ДНЯХ ПРОДАЖИ (переименована из "Запас, дни")
-- остаётся WB-only — меры "запас в днях" для Ozon/Yandex в модели нет,
-- NULL для этих строк.
--
-- ОБНОВЛЕНИЕ 03.08.2026 (запрос пользователя):
--   • "Цена в ЛК" — больше не WB-only. Ozon и Yandex теперь выгружают свою
--     базовую цену из профиля товара (см. dax_queries.py: '_МЕРЫ OZON'[Цена в
--     ЛК, руб Oz] и '_МЕРЫ YAM'[Цена в ЛК, руб Yam]), поэтому в их ветках
--     UNION колонка больше не NULL. NULL остаётся только в складской ветке.
--     ВНИМАНИЕ: у Ozon/Yandex источник — ежедневные снимки цен
--     (ozon_daily_prices / ya_daily_prices_lk), история в них началась
--     03.08.2026, поэтому за более ранние даты колонка будет пустой.
--   • "Цена на WB" ЗАМЕНЕНА на "Цена на МП" — не добавлена рядом, а именно
--     заняла её позицию в списке колонок, порядок остальных не изменился.
--     Смысл тот же (цена, которую реально видит покупатель после скидок
--     маркетплейса), но теперь колонка заполнена у всех трёх МП, а не
--     только у WB: WB — [Цена на WB], Ozon — [Цена на МП, руб Oz],
--     Yandex — [Цена на МП, руб Yam]. Общее число колонок в каждой ветке
--     UNION осталось прежним.
--   • "FR_Продажи, шт." переименована в "FR_Заказы, шт." во всех ветках И в
--     dax_queries.py (сама мера в модели не менялась — это то же количество
--     ДО вычета возвратов: Заказы − Возвраты = Выкупы).
--   • "Выручка выкупов по цене в ЛК, руб" = "FR_Выкупы, шт" × "Цена в ЛК" —
--     новая расчётная колонка, добавлена ПОСЛЕДНЕЙ в каждой ветке UNION.
--     Считается прямо здесь, в Postgres (оба слагаемых уже есть в
--     fact_revenue_*), рейс в Power BI не нужен. Смысл: сколько бы принесли
--     фактические выкупы, если бы товар продавался по цене из ЛК — разница
--     с "FR_Выручка по выкупам, руб" показывает потери на скидках МП.
--     ИМЯ КОЛОНКИ: изначально было "Выручка по выкупам по цене в ЛК, руб" —
--     64 байта в UTF-8, а лимит идентификатора в Postgres 63 байта, поэтому
--     psql резал его до "Выручка по выкупам по цене в ЛК, ру" (NOTICE при
--     CREATE VIEW). Переименовано в "Выручка выкупов по цене в ЛК, руб"
--     (59 байт). ПРИ ДОБАВЛЕНИИ НОВЫХ КОЛОНОК: кириллица в UTF-8 занимает
--     2 байта на букву, то есть в имя влезает примерно 31 кириллический
--     символ вместе с пробелами и запятыми.
--     ЕСЛИ ПРИ CREATE VIEW ПОЯВИТСЯ ОШИБКА "operator does not exist: text *
--     text" — значит pandas.to_sql записал одну из колонок как text (см.
--     комментарий про разнотипность в начале файла); тогда оберните обе в
--     NULLIF(...::text,'')::numeric или поменяйте тип колонки в БД.
--   • "FR_Скидки МП" для Yandex НЕ менялась в этих файлах — она и так брала
--     '_МЕРЫ YAM'[Скидки МП, руб Yam]. Исправлена сама мера в модели PBI:
--     раньше её формула ([Продажи] − [Выручка по выкупам]) алгебраически
--     схлопывалась в [Возвраты, руб Yam]; теперь это настоящая сумма скидок
--     за счёт Маркета. Достаточно перезапустить pbi_to_postgres.py — цифры
--     в колонке изменятся сами.
--
-- ВАЖНО: скрипт сам дропает и пересоздаёт v_marketplaces_raw_union и
-- v_marketplaces_full (см. DROP ниже) — можно запускать самостоятельно, не
-- только сразу после pbi_to_postgres.py.

DROP VIEW IF EXISTS v_marketplaces_full CASCADE;
DROP VIEW IF EXISTS v_marketplaces_raw_union CASCADE;

-- 1) Объединение трёх маркетплейсов в одну таблицу (аналог UNION в DAX).
--    WB-специфичные колонки (клики/корзины/CR/остатки/т.п.) у Ozon и Yandex
--    заполняются NULL — как раньше BLANK() в DAX.
-- СКЛАДСКОЙ БЛОК (по запросу пользователя: "меры по складу и то, что на
-- отдельных листах, должно быть в v_marketplaces_full, только у него
-- Маркетплейс пустой, ключ — Дата+SKU+Направление") — добавлен четвёртой
-- веткой UNION ALL ниже (см. её после веток WB/Ozon/Yandex).
-- Состав: FBS-остатки из v_warehouse_stocks_fbs (Доступно/Зарезервировано/
-- Отгружается/Всего/Заказано/В пути), агрегированные SUM() по складам
-- (в v_marketplaces_full нет измерения "Склад", а v_warehouse_stocks_fbs
-- грейнится по Дата+SKU+Склад).
-- ФИЛЬТР ПО СКЛАДАМ (по запросу пользователя): в fbs_agg суммируются
-- ТОЛЬКО склады из списка ниже (WHERE h."Склад" IN (...)) — остальные
-- склады в quantity_instock/"Доступно" не учитываются. Фильтр действует
-- только здесь, на v_marketplaces_full; сама v_warehouse_stocks_fbs (лист
-- "Остатки FBS", daily_sales_report.py, telegram_bot.py) не меняется и
-- продолжает отдавать все склады без ограничений.
-- "Остаток (все источники), шт" на складской строке считается НАПРЯМУЮ как
-- Всего(FBS) + Остаток FBO (суммарно WB+Ozon+Yandex, CTE fbo_agg, только
-- для этого расчёта) + В пути(FBS) — а не отдельно через v_stocks_all_total
-- (тот раньше считал FBS-часть по ВСЕМ складам без фильтра выше и по
-- "Доступно", а не "Всего", плюс не учитывал "В пути" — равенство не
-- сходилось).
-- ВАЖНО: сама колонка "Остаток FBO, шт" на складской строке остаётся NULL
-- (сюда её сознательно НЕ выводим, хотя внутри fbo_agg сумма посчитана) —
-- те же цифры по WB/Ozon/Yandex уже есть по отдельности на WB/Ozon/Yandex-
-- строках в колонке "Остаток FBO, шт". Если вывести сумму ещё и на
-- складской строке, простой SUM() по столбцу в Google Sheets задвоит
-- FBW/Ozon/Yandex остатки (было проверено на практике на Направление=
-- Echips, Дата=08.08 — сумма трёх колонок разошлась с "Остаток (все
-- источники)" ровно на задвоенный FBO).
-- "SKU (ключ)"/"Направление" для складских строк получаем через JOIN на
-- dim_sku по UPPER(articul) = dim_sku."SKU_upper" — то же сопоставление,
-- что использовано в history.SQL для v_stocks_all_total/v_stocks_by_marketplace.
--
-- ВАЖНО (порядок запуска): т.к. v_marketplaces_raw_union теперь читает
-- v_warehouse_stocks_fbs (history.SQL), history.SQL нужно выполнять ДО
-- join_marketplaces.sql (иначе — "relation ... does not exist").
CREATE VIEW v_marketplaces_raw_union AS
WITH fbs_agg AS (
    SELECT
        UPPER(h."SKU")             AS "SKU_upper",
        h."Дата"                    AS "Date",
        SUM(h."Доступно")           AS "Доступно (FBS), шт",
        SUM(h."Зарезервировано")    AS "Зарезервировано (FBS), шт",
        SUM(h."Отгружается")        AS "Отгружается (FBS), шт",
        SUM(h."Всего")               AS "Всего (FBS), шт",
        SUM(h."Заказано")            AS "Заказано (FBS), шт",
        SUM(h."В пути")              AS "В пути (FBS), шт"
    FROM public.v_warehouse_stocks_fbs h
    WHERE h."SKU" IS NOT NULL
      AND h."Склад" IN (
        'Авито',
        'Б/У запчасти',
        'Блогеры',
        'Брак',
        'Запчасти (Челябинск)',
        'Ожидает запчасти',
        'Подменные ноутбуки Челябинск',
        'Ремонт',
        'Челябинск',
        'Рязанка склад Москва'
      )
    GROUP BY UPPER(h."SKU"), h."Дата"
),
-- Остаток FBO агрегированный по ВСЕМ маркетплейсам (WB+Ozon+Yandex) на
-- SKU+Дату — нужен только для складской ветки ниже, чтобы "Остаток (все
-- источники), шт" считался напрямую как Всего(FBS) + Остаток FBO + В
-- пути(FBS), а не отдельно из v_stocks_all_total (там FBS-часть считалась
-- по ВСЕМ складам без фильтра выше и по "Доступно", а не "Всего" — из-за
-- этого равенство не сходилось). Логика та же, что в v_stocks_all_total
-- (history.SQL, раздел 6), но без FBS-ветки.
fbo_agg AS (
    SELECT "Date", "SKU_upper", SUM("Остаток") AS "Остаток FBO, шт"
    FROM (
        SELECT wb."Date"::date AS "Date", UPPER(wb."SKU (ключ)") AS "SKU_upper", SUM(wb."Остаток FBW, шт") AS "Остаток"
        FROM public.fact_revenue_wb wb
        WHERE wb."Остаток FBW, шт" IS NOT NULL AND wb."SKU (ключ)" IS NOT NULL
        GROUP BY wb."Date", UPPER(wb."SKU (ключ)")

        UNION ALL

        SELECT oz."Date"::date AS "Date", UPPER(oz."SKU (ключ)") AS "SKU_upper", SUM(oz."Остаток Ozon, шт") AS "Остаток"
        FROM public.fact_revenue_ozon oz
        WHERE oz."Остаток Ozon, шт" IS NOT NULL AND oz."SKU (ключ)" IS NOT NULL
        GROUP BY oz."Date", UPPER(oz."SKU (ключ)")

        UNION ALL

        SELECT ya."Date"::date AS "Date", UPPER(ya."SKU (ключ)") AS "SKU_upper", SUM(ya."Остаток Yandex, шт") AS "Остаток"
        FROM public.fact_revenue_yandex ya
        WHERE ya."Остаток Yandex, шт" IS NOT NULL AND ya."SKU (ключ)" IS NOT NULL
        GROUP BY ya."Date", UPPER(ya."SKU (ключ)")
    ) combined
    GROUP BY "Date", "SKU_upper"
)
SELECT
