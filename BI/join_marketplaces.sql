    "ROI",
    -- FR_-блок в запрошенном пользователем порядке (см. комментарий выше).
    "FR_Заказы, шт.",
    "FR_Возвраты, шт.",
    "FR_Сумма возвратов, руб",
    "FR_Выкупы, шт",
    "FR_Продажи до скидок с НДС",
    "FR_Скидки МП",
    "FR_Выручка по выкупам, руб",
    "FR_Комиссия",
    "FR_Эквайринг",
    "FR_Логистика прямая",
    "FR_Обратная и прочая логистика",
    "FR_Прочие удержания",
    NULL::numeric                            AS "FR_Прочие списания, руб",
    "FR_Продвижение, руб",
    "FR_Выручка по выкупам без НДС, руб",
    "FR_MP Cost с НДС, руб",
    "FR_НДС вычет на MP Cost",
    "FR_Себес УУс",
    "FR_Маржа, руб",
    "Остаток FBW, шт"                       AS "Остаток FBO, шт",
    "Запас, дни"                             AS "Запас ФБО в днях продажи",
    ("FR_Выручка по выкупам, руб" - "FR_MP Cost с НДС, руб") AS "FR_Дебиторка с НДС, руб",
    "FR_Выручка по заказам, руб",
    NULL::numeric                            AS "Доступно (FBS), шт",
    NULL::numeric                            AS "Зарезервировано (FBS), шт",
    NULL::numeric                            AS "Отгружается (FBS), шт",
    NULL::numeric                            AS "Всего (FBS), шт",
    NULL::numeric                            AS "Заказано (FBS), шт",
    NULL::numeric                            AS "В пути (FBS), шт",
    NULL::numeric                            AS "Остаток (все источники), шт",
    ("FR_Выкупы, шт" * "Цена в ЛК")           AS "Выручка выкупов по цене в ЛК, руб"
FROM fact_revenue_wb

UNION ALL

SELECT
