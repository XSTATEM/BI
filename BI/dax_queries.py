    #
    # ЗНАК: мера [Прочее, руб Oz] умножает исходную сумму на -1, поэтому расход
    # здесь ПОЛОЖИТЕЛЬНЫЙ (в сырых данных Ozon удержания идут с минусом). В
    # образце-сводной знак противоположный. Если нужно как в образце — убрать
    # ниже "* -1" ... точнее, обернуть меру: "Прочие удержания, руб", -[_v].
    #
    # Состав "Прочего" у Ozon разношёрстный (подписка Premium Plus, упаковка,
