    # (грейн SKU+Дата+Маркетплейс дал бы задвоение/затроение при SUM()).
    # Проверено эмпирически (SUMX по SKU через SUMMARIZE = общий ИТОГО без
    # группировки), что меры корректно относят сумму к каждому SKU без
