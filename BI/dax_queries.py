    # --- Прочие удержания Ozon в разрезе кабинет + тип начисления -----------
    # Отдельный датасет под отдельный лист Google Sheets (запрос пользователя).
    # Грейн: Дата + Магазин (кабинет) + Тип начисления, БЕЗ SKU. В образце-
    # сводной даты не было (один итог за весь период), но по решению
    # пользователя колонка "Дата" добавлена ПЕРВОЙ, чтобы лист можно было
    # резать по месяцам/неделям сводной в Google Sheets. Период — те же
